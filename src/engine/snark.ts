const pick = <T>(xs: readonly T[], rand: Rand): T => xs[Math.floor(rand() * xs.length) % xs.length]

/** n distinct items from xs, in random order */
function sample<T>(xs: readonly T[], n: number, rand: Rand): T[] {
  const pool = [...xs]
  const out: T[] = []
  while (out.length < n && pool.length) out.push(pool.splice(Math.floor(rand() * pool.length) % pool.length, 1)[0])
  return out
}

export interface SnarkInput {
  name?: string
  tier?: string
  tags: SnarkTag[]
  /** the previous roll; its lines are skipped so re-rolls feel fresh */
  avoid?: string
}

/** A few sentences of System AI snark: opener, one or two lines per tag, maybe a tier jab, closer. */
export function generateSnark({ name, tier, tags, avoid }: SnarkInput, rand: Rand = Math.random): string {
  const fresh = (xs: readonly string[]) => {
    const left = avoid ? xs.filter((x) => !avoid.includes(x)) : xs
    return pick(left.length ? left : xs, rand)
  }
  const parts = [fresh(OPENERS)]
  const title = name?.trim()
  if (title) parts.push(`You have earned the ${title.replace(/[.!]+$/, '')} achievement.`)
  const chosen = sample(tags, 2, rand)
  if (chosen.length) for (const t of chosen) parts.push(fresh(CORES[t]))
  else parts.push(fresh(GENERIC_CORES))
  const remarks = tier ? TIER_REMARKS[tier] : undefined
  if (remarks && rand() < 0.5) parts.push(fresh(remarks))
  parts.push(fresh(CLOSERS))
  return parts.join(' ')
}

/** Achievement name ideas for the chosen tags (generic ones when none are picked). */
export function generateNames(tags: SnarkTag[], count = 5, rand: Rand = Math.random): string[] {
  const pool = tags.length ? [...new Set(tags.flatMap((t) => NAMES[t]))] : GENERIC_NAMES
  return sample(pool, count, rand)
}

